// Content coverage against the curriculum and the docs/05 ship rule. Pure over the validated manifest,
// so content:validate can regenerate the report and the roadmap's readiness labels on every run.
import type { Manifest } from "@/src/content/catalog";
import type { LessonEntry } from "@/src/content/lessons";
import { chapters, foundationById, foundationsUsedBy, skillsOfChapter } from "@/src/domain/curriculum";

export type Readiness = "preview" | "partial" | "practice" | "ready";
export interface SkillCoverage {
  skillId: string; title: string; required: boolean;
  /** playable templates per difficulty, and how many of them are human-approved */
  counts: Record<"easy" | "medium" | "hard", { playable: number; approved: number }>;
  widgets: string[];
  lesson: boolean;
}
export interface ChapterCoverage {
  chapterId: string; title: string; readiness: Readiness;
  skills: SkillCoverage[];
  foundations: { id: string; title: string; practice: number; lesson: boolean }[];
  gaps: string[];
}

const DIFFS = ["easy", "medium", "hard"] as const;
/** docs/05 ship rule: at least this many approved templates per skill at each difficulty selection can request */
export const SHIP_RULE_PER_DIFFICULTY = 2;

export function coverage(manifest: Manifest, lessons: LessonEntry[]): ChapterCoverage[] {
  const bySkill = (id: string) => manifest.templates.filter((e) => e.template.primarySkillId === id);
  const hasLesson = (id: string) => lessons.some((l) => l.lesson.skillId === id);
  return chapters.map((c) => {
    const skills: SkillCoverage[] = skillsOfChapter(c.id).map((s) => {
      const list = bySkill(s.id);
      const counts = Object.fromEntries(DIFFS.map((d) => {
        const at = list.filter((e) => e.template.difficulty === d);
        return [d, { playable: at.length, approved: at.filter((e) => e.countsTowardMastery).length }];
      })) as SkillCoverage["counts"];
      return { skillId: s.id, title: s.title, required: s.required, counts, widgets: [...new Set(list.map((e) => e.template.widget.type))].sort(), lesson: hasLesson(s.id) };
    });
    const foundations = foundationsUsedBy(c.id).map((f) => ({ id: f.id, title: f.title, practice: bySkill(f.id).length, lesson: hasLesson(f.id) }));
    const req = skills.filter((s) => s.required);
    const anyMain = skills.some((s) => s.counts.medium.playable + s.counts.hard.playable > 0);
    const allPractice = req.every((s) => DIFFS.every((d) => s.counts[d].playable > 0));
    const shipRule = req.every((s) => DIFFS.every((d) => s.counts[d].approved >= SHIP_RULE_PER_DIFFICULTY)) && foundations.every((f) => f.lesson && f.practice > 0);
    const readiness: Readiness = !anyMain ? "preview" : shipRule ? "ready" : allPractice ? "practice" : "partial";
    const gaps: string[] = [];
    for (const s of req) {
      const missing = DIFFS.filter((d) => s.counts[d].playable === 0);
      if (missing.length) gaps.push(`${s.skillId}: no ${missing.join("/")} template`);
    }
    const unapproved = req.filter((s) => DIFFS.some((d) => s.counts[d].approved < SHIP_RULE_PER_DIFFICULTY)).length;
    if (unapproved) gaps.push(`ship rule: ${unapproved} of ${req.length} required skills lack ${SHIP_RULE_PER_DIFFICULTY} approved templates at every difficulty`);
    const noLesson = foundations.filter((f) => !f.lesson).map((f) => f.id);
    const noPractice = foundations.filter((f) => f.practice === 0).map((f) => f.id);
    if (noPractice.length) gaps.push(`foundations without practice: ${noPractice.join(", ")}`);
    if (noLesson.length) gaps.push(`foundations without a micro-lesson: ${noLesson.join(", ")}`);
    return { chapterId: c.id, title: c.title, readiness, skills, foundations, gaps };
  });
}

const LABEL: Record<Readiness, string> = {
  preview: "Preview only",
  partial: "Partial practice",
  practice: "Practice ready, awaiting review",
  ready: "Ready (ship rule met)",
};

export function coverageMarkdown(rows: ChapterCoverage[], manifest: Manifest, lessons: LessonEntry[]): string {
  const cell = (s: SkillCoverage, d: (typeof DIFFS)[number]) => {
    const x = s.counts[d];
    return x.playable === 0 ? "—" : `${x.playable}${x.approved ? ` (${x.approved}✓)` : ""}`;
  };
  const total = manifest.templates.length, approved = manifest.templates.filter((e) => e.countsTowardMastery).length;
  let md = `# Content coverage (generated)\n\n> GENERATED by \`npm run content:validate\` from the validated manifest and the curriculum. Do not edit.\n\n`;
  md += `${total} playable templates (${approved} human-approved), ${lessons.length} lessons (${lessons.filter((l) => l.approved).length} approved). Counts are playable templates per difficulty; ✓ marks human-approved ones. The ship rule needs ${SHIP_RULE_PER_DIFFICULTY} approved templates per required skill at each difficulty plus a micro-lesson and practice for each foundation a chapter uses directly.\n\n`;
  md += `| Chapter | Readiness | Required skills with easy/medium/hard | Interactive models |\n|---|---|---|---|\n`;
  for (const r of rows) {
    const req = r.skills.filter((s) => s.required);
    const full = req.filter((s) => DIFFS.every((d) => s.counts[d].playable > 0)).length;
    md += `| ${r.title} | ${LABEL[r.readiness]} | ${full}/${req.length} | ${[...new Set(r.skills.flatMap((s) => s.widgets))].sort().join(", ") || "—"} |\n`;
  }
  for (const r of rows) {
    md += `\n## ${r.title} (\`${r.chapterId}\`) · ${LABEL[r.readiness]}\n\n| Skill | Easy | Medium | Hard | Models | Lesson |\n|---|---|---|---|---|---|\n`;
    for (const s of r.skills) md += `| \`${s.skillId}\`${s.required ? "" : " (optional)"} ${s.title} | ${cell(s, "easy")} | ${cell(s, "medium")} | ${cell(s, "hard")} | ${s.widgets.join(", ") || "—"} | ${s.lesson ? "yes" : "—"} |\n`;
    if (r.foundations.length) md += `\nFoundations used directly: ${r.foundations.map((f) => `${f.title} (${f.practice} practice${f.lesson ? ", lesson" : ""})`).join("; ")}.\n`;
    if (r.gaps.length) md += `\nRemaining gaps:\n${r.gaps.map((g) => `- ${g}`).join("\n")}\n`;
  }
  const allF = [...foundationById.values()];
  md += `\n## Foundations\n\n| Foundation | Practice templates | Micro-lesson |\n|---|---|---|\n`;
  for (const f of allF) md += `| \`${f.id}\` ${f.title} | ${manifest.templates.filter((e) => e.template.primarySkillId === f.id).length} | ${lessons.some((l) => l.lesson.skillId === f.id) ? "yes" : "—"} |\n`;
  return md;
}

/** What the roadmap needs to label chapters honestly (small; bundled with the map). */
export const readinessJson = (rows: ChapterCoverage[]) =>
  Object.fromEntries(rows.map((r) => {
    const req = r.skills.filter((s) => s.required);
    return [r.chapterId, { readiness: r.readiness, requiredSkills: req.length, skillsWithPractice: req.filter((s) => s.counts.medium.playable + s.counts.hard.playable > 0).length }];
  }));
