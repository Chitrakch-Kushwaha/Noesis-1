#!/usr/bin/env node
// Chooses which live tutor adapter is compiled into the app by rewriting
// src/tutor/server/adapters.generated.ts. Selecting an adapter does not activate anything: live
// tutoring still needs the activation record, the server environment and credentials (docs/09).
//
//   npm run tutor:select-adapter -- --provider openai          (or gemini, or openai,gemini)
//   npm run tutor:select-adapter -- --provider none      (the default: no vendor code in the build)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const target = join(root, "src", "tutor", "server", "adapters.generated.ts");

/** adapters that exist in adapters/<name>/ and the factory each exports */
export const KNOWN_ADAPTERS = {
  openai: { module: "@/adapters/openai", factory: "createOpenAIAdapter" },
  gemini: { module: "@/adapters/gemini", factory: "createGeminiAdapter" },
};

export function registrySource(provider) {
  const head = "// Generated by `npm run tutor:select-adapter`. Do not edit by hand.\n";
  if (provider === "none") {
    return head +
      "// Default: no live adapter is compiled into the app, so the student build contains no AI vendor code or host.\n" +
      'import type { AdapterFactory } from "./adapterTypes";\n\n' +
      "export const SELECTED_ADAPTER: string | null = null;\n" +
      "export const ADAPTERS: Record<string, AdapterFactory> = {};\n";
  }
  const names = provider.split(",");
  return head +
    `// Compiled in: ${names.join(", ")}. Used only when every activation gate is met (src/tutor/server/activation.ts).\n` +
    'import type { AdapterFactory } from "./adapterTypes";\n' +
    names.map((n) => `import { ${KNOWN_ADAPTERS[n].factory} } from "${KNOWN_ADAPTERS[n].module}";\n`).join("") +
    `\nexport const SELECTED_ADAPTER: string | null = ${JSON.stringify(names.join(","))};\n` +
    `export const ADAPTERS: Record<string, AdapterFactory> = { ${names.map((n) => `${n}: ${KNOWN_ADAPTERS[n].factory}`).join(", ")} };\n`;
}

/** the provider named in the current registry, or null */
export function selectedAdapter(source = readFileSync(target, "utf8")) {
  const m = /SELECTED_ADAPTER: string \| null = (null|"([a-z0-9,-]+)")/.exec(source);
  return m && m[2] ? m[2] : null;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const i = process.argv.indexOf("--provider");
  const provider = i > 0 ? process.argv[i + 1] : undefined;
  if (!provider || (provider !== "none" && !provider.split(",").every((n) => n in KNOWN_ADAPTERS))) {
    console.error(`Usage: npm run tutor:select-adapter -- --provider ${["none", ...Object.keys(KNOWN_ADAPTERS)].join("|")}[,…]`);
    process.exit(2);
  }
  writeFileSync(target, registrySource(provider));
  console.log(provider === "none"
    ? "No live tutor adapter is compiled in (default)."
    : `The ${provider} adapter will be compiled in at the next build. This does not activate live tutoring: see docs/09 for the activation gates.`);
}
