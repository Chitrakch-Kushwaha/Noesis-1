// Micro-lessons and detour explainers (docs/04 "Foundation leaves", docs/07). A lesson is a short,
// scrubbable sequence of steps that drive one live widget through the same cue system as questions.
// Like templates, lessons are JSON content with a status and a human review record.
import generated from "./generated/lessons.json";
import { z } from "zod";
import { STATUSES } from "./schema";

const CueSchema = z.object({ cue: z.string(), args: z.record(z.string(), z.unknown()).optional() });
const Cues = z.union([CueSchema, z.array(CueSchema)]);
const Step = z.object({ text: z.string().min(1), cue: Cues.optional() });
const Widget = z.object({ type: z.string(), config: z.record(z.string(), z.unknown()), instructions: z.string().min(10) });

export const LessonSchema = z.object({
  id: z.string().regex(/^[a-z0-9]+\.[a-z0-9-]+\.lesson$/),
  version: z.number().int().positive(),
  status: z.enum(STATUSES),
  provenance: z.object({
    origin: z.enum(["human", "ai-draft"]),
    author: z.string(),
    createdAt: z.string(),
    reviewedBy: z.string().nullable(),
    reviewedAt: z.string().nullable(),
    contentHash: z.string().nullable(),
    reviewLog: z.array(z.object({ at: z.string(), by: z.string(), decision: z.enum(["approved", "changes-requested", "submitted"]), note: z.string() })).default([]),
  }),
  skillId: z.string(),
  /** micro-lesson: the teaching core of a foundation frame. explainer: the short opener of a detour. */
  kind: z.enum(["micro-lesson", "explainer"]),
  title: z.string().min(3),
  minutes: z.number().positive().max(15),
  widget: Widget,
  steps: z.array(Step).min(3).max(8),
  /** a second representation, used when the micro-lesson is repeated */
  alternate: z.object({ title: z.string().min(3), widget: Widget.optional(), steps: z.array(Step).min(2).max(8) }).optional(),
  /** a 30-second recap offered when a paused foundation frame is resumed */
  recap: z.array(Step).min(1).max(3).optional(),
  accessibility: z.object({ altText: z.string().min(10), nonDragAlternative: z.string().optional() }),
});
export type Lesson = z.infer<typeof LessonSchema>;
export type LessonStep = z.infer<typeof Step>;
export type LessonVariant = "main" | "alternate" | "recap";

const asCues = (c: LessonStep["cue"]) => (c ? (Array.isArray(c) ? c : [c]) : []);
export const lessonCues = asCues;

/** The widget and steps shown for one variant of a lesson. */
export function lessonVariant(l: Lesson, v: LessonVariant): { title: string; widget: Lesson["widget"]; steps: LessonStep[] } {
  if (v === "alternate" && l.alternate) return { title: l.alternate.title, widget: l.alternate.widget ?? l.widget, steps: l.alternate.steps };
  if (v === "recap" && l.recap) return { title: `${l.title}: recap`, widget: l.widget, steps: l.recap };
  return { title: l.title, widget: l.widget, steps: l.steps };
}

/** Lessons that ship to students (generated by content:validate: valid, in-review or approved). */
export interface LessonEntry { lesson: Lesson; hash: string; approved: boolean }
export const LESSONS: LessonEntry[] = (generated as unknown as { lessons: LessonEntry[] }).lessons;
export const lessonForSkill = (skillId: string) => LESSONS.find((e) => e.lesson.skillId === skillId);
